import assert from "node:assert/strict";
import { fitColumnWidths } from "../src/table_width_fit.ts";
import { routeTableId, routeTableLabel, remainingPlanSeconds } from "../src/network_display.ts";
const col=(key,auto,max=480,manual)=>({key,min:40,max,auto,manual});
assert.deepEqual(fitColumnWidths([col("a",100),col("b",200)],600),{a:200,b:400});
assert.deepEqual(fitColumnWidths([col("a",100,150),col("b",100)],500),{a:150,b:350});
assert.deepEqual(fitColumnWidths([col("a",100,480,80),col("b",100)],500),{a:80,b:420});
assert.deepEqual(fitColumnWidths([col("a",300),col("b",400)],500),{a:300,b:400});
assert.deepEqual(fitColumnWidths([col("a",100,100),col("b",100,100)],500),{a:100,b:100});
assert.deepEqual(fitColumnWidths([col("a",100,480,90),col("b",100,480,100)],500),{a:90,b:100});
const rounded=fitColumnWidths([col("a",81),col("b",117),col("c",75)],499);
assert.equal(Object.values(rounded).reduce((a,b)=>a+b,0),499);
for (const width of Object.values(rounded)) assert.ok(Number.isInteger(width)&&width>=40&&width<=480);
assert.equal(routeTableId("main"),"254");assert.equal(routeTableLabel(254),"254 · main");
assert.equal(routeTableLabel("local"),"255 · local");assert.equal(routeTableLabel(65743),"65743");
assert.equal(routeTableId(0),"0");assert.equal(routeTableId("custom-table"),"custom-table");
assert.equal(remainingPlanSeconds(1000,880),120);assert.equal(remainingPlanSeconds(1000,999.6),1);
assert.equal(remainingPlanSeconds(1000,1001),0);assert.equal(remainingPlanSeconds(NaN,1),0);
console.log("Network UI v0.9.3-11: proportional widths, bounds, manual pins, table aliases and deadlines passed.");
